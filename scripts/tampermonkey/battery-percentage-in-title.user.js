(function() {
    'use strict';
    let ipPart = '';
    let jsonEndpoint = window.location.origin;

    const originalTitle = document.title;

    const ipAddress = jsonEndpoint.match(/(?:\d{1,3}\.){3}(\d{1,3})/);
    if (ipAddress) {
        ipPart = ipAddress[1];
    }

    function updateBatteryPercentage() {
        // console.log("Running request to:", originalTitle, ipPart, jsonEndpoint);

        GM_xmlhttpRequest({
            method: "GET",
            url: `${jsonEndpoint}/status.json`,
            onload: function(response) {
                if (response.status === 200) {
                    try {
                        const data = JSON.parse(response.responseText);
                        const batteryPercentage = data.deviceInfo.batteryPercent;

                        if (batteryPercentage !== undefined) {
                            document.title = `${batteryPercentage}% ${ipPart} - ${originalTitle}`;
                            console.log(`Setting battery to: ${batteryPercentage}%`);
                        }
                        else {
                            console.log(`Invalid response, missing baterry info: ${response.responseText}.`);
                        }
                    } catch (e) {
                        console.error("Failed to parse JSON:", e);
                    }
                } else {
                    console.error("Failed to fetch data:", response.statusText);
                }
            },
            onerror: function(e) {
                console.error("Error fetching data:", e);
            }
        });
    }

    console.log("Starting up:", originalTitle, jsonEndpoint);

    setInterval(updateBatteryPercentage, 60000);

    updateBatteryPercentage();
})();
